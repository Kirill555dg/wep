export const runManualTest = (scenarioId: string) => {
  const { tests } = userScenarios()
  
  for (const suite of tests) {
    const scenario = suite.scenarios.find(s => s.id === scenarioId)
    if (scenario) {
      console.log(`\n🧪 ${suite.name} - ${scenario.name}`)
      console.log(`\nШаги сценария:`)
      scenario.steps.forEach((step, index) => {
        console.log(`${index + 1}. ${step}`)
      })
      console.log(`\nОжидаемый результат: ${scenario.expected}`)
      console.log(`\nДля выполнения: откройте ${BASE_URL}${getBaseUrl(scenarioId)}`)
      return
    }
  }
  
  console.log(`Сценарий ${scenarioId} не найден`)
}

const getBaseUrl = (scenarioId: string): string => {
  if (scenarioId.startsWith('auth')) return '/login'
  if (scenarioId.startsWith('catalog')) return '/catalog'
  if (scenarioId.startsWith('dashboard')) return '/dashboard'
  return '/'
}

const BASE_URL = 'http://localhost:5173'